#!/bin/sh
# Generate chronological round indexes. --check compares without editing files.
set -eu
CHECK=0
[ "${1:-}" != '--check' ] || { CHECK=1; shift; }
ROOT="${1:-$(cd "$(dirname "$0")/.." && pwd)}"
python3 - "$ROOT" "$CHECK" <<'PY'
from pathlib import Path
import re,sys
root=Path(sys.argv[1]);check=sys.argv[2]=='1';stale=False
for program in sorted((root/'programs').iterdir()):
    folder=program/'recon/rounds'
    if not folder.is_dir():continue
    files=[p for p in folder.glob('*.md') if re.match(r'^(round-|discovery-|cycle)',p.name)]
    def timestamp(path):
        m=re.search(r'(\d{8})T(\d{4,6})Z',path.stem)
        return m[1]+'T'+m[2].ljust(6,'0')+'Z' if m else ''
    lines=[f'# {program.name} round index','',
           'Generated by `tools/build-rounds.sh`, newest UTC observation first.',
           'Recorded means an artifact exists; it does not certify a successful probe.','',
           '| Round (UTC) | Mode | Job | Status |','|---|---|---|---|']
    for p in sorted(files,key=lambda p:(timestamp(p),p.name),reverse=True):
        text=p.read_text()
        mode=re.search(r'^# *Round .*?[—-] *mode *([a-z0-9]+)',text,re.M)
        mode=mode[1] if mode else 'discovery' if p.name.startswith('discovery-') else 'cycle'
        def field(name):
            m=re.search(r'^- *'+name+r': *`([^`]+)`',text,re.M)
            return m[1] if m else '—'
        label=re.sub(r'^(round-|discovery-)','',p.stem)
        status=field('status')
        lines.append(f'| [{label}](recon/rounds/{p.name}) | {mode} | {field("job")} | {status if status != "—" else "recorded"} |')
    result='\n'.join(lines)+'\n';output=program/'ROUNDS.md'
    if check:
        if not output.is_file() or output.read_text()!=result:
            print(f'STALE: {output.relative_to(root)}');stale=True
    else:
        output.write_text(result);print(f'Wrote {output.relative_to(root)}')
sys.exit(1 if stale else 0)
PY
